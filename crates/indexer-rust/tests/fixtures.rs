//! Fixture parity: every `<fixture>.<ext>` beside a `<fixture>.expected.json` must
//! extract to exactly the JS extractor's answer.
//!
//! The expectations are written by `tools/gen-expected.mjs` running
//! `packages/tree-sitter/src/extract.ts` — the JS side is the behaviour spec, this
//! crate is measured against it, never the other way round.

use std::fs;
use std::path::{Path, PathBuf};

use dsh_plugin_codegraph_indexer::{extract_file, parse_rules, LanguageSpec};
use serde_json::Value;
use tree_sitter::{Language, Parser};

fn fixtures_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests").join("fixtures")
}

fn supported_specs() -> Vec<LanguageSpec> {
    let rules = fs::read_to_string(fixtures_root().join("language-rules.json"))
        .expect("tests/fixtures/language-rules.json is generated by tools/gen-expected.mjs");
    parse_rules(&rules).expect("language-rules.json parses as LanguageSpec[]")
}

fn grammar(language: &str) -> Language {
    match language {
        "typescript" => tree_sitter_typescript::LANGUAGE_TYPESCRIPT.into(),
        "tsx" => tree_sitter_typescript::LANGUAGE_TSX.into(),
        "javascript" | "jsx" => tree_sitter_javascript::LANGUAGE.into(),
        other => panic!("fixture asks for unsupported language {other:?}"),
    }
}

/// One fixture pair: source text, its language spec, and the JS-written expectation.
struct Fixture {
    name: String,
    language: String,
    source: String,
    expected: Value,
}

/// Fixture directory -> the seam language every file in it is parsed as, matching how
/// `languageFor` routes extensions (`ts`/`tsx`/`js`/`jsx` groups).
const GROUPS: [(&str, &str); 4] = [
    ("ts", "typescript"),
    ("tsx", "tsx"),
    ("js", "javascript"),
    ("jsx", "jsx"),
];

fn collect_fixtures() -> Vec<Fixture> {
    let specs = supported_specs();
    let mut fixtures = Vec::new();
    for (group, language) in GROUPS {
        let spec = specs
            .iter()
            .find(|spec| spec.language == language)
            .unwrap_or_else(|| panic!("language-rules.json has no {language:?} spec"));
        let directory = fixtures_root().join(group);
        let mut names: Vec<String> = fs::read_dir(&directory)
            .unwrap_or_else(|error| panic!("cannot read {}: {error}", directory.display()))
            .map(|entry| entry.expect("dir entry").file_name().to_string_lossy().into_owned())
            .collect();
        names.sort();
        for name in names {
            if name.ends_with(".expected.json") {
                continue;
            }
            let source_path = directory.join(&name);
            let expected_path = source_path.with_extension("expected.json");
            let source = fs::read_to_string(&source_path)
                .unwrap_or_else(|error| panic!("cannot read {}: {error}", source_path.display()));
            let expected_json = fs::read_to_string(&expected_path).unwrap_or_else(|error| {
                panic!(
                    "missing {} ({error}); regenerate with `node --experimental-strip-types tools/gen-expected.mjs`",
                    expected_path.display()
                )
            });
            fixtures.push(Fixture {
                name: source_path
                    .strip_prefix(fixtures_root())
                    .expect("fixture under root")
                    .display()
                    .to_string(),
                language: spec.language.clone(),
                source,
                expected: serde_json::from_str(&expected_json)
                    .unwrap_or_else(|error| panic!("invalid {}: {error}", expected_path.display())),
            });
        }
    }
    fixtures
}

/// The first structural difference between two JSON values, as a path plus both sides —
/// far more useful than a multi-megabyte `assert_eq!` dump on a large fixture.
fn first_difference(path: &str, expected: &Value, actual: &Value) -> Option<String> {
    match (expected, actual) {
        (Value::Object(expected), Value::Object(actual)) => {
            for (key, expected_value) in expected {
                match actual.get(key) {
                    Some(actual_value) => {
                        if let Some(difference) =
                            first_difference(&format!("{path}.{key}"), expected_value, actual_value)
                        {
                            return Some(difference);
                        }
                    }
                    None => return Some(format!("{path}.{key}: missing from Rust output")),
                }
            }
            for key in actual.keys() {
                if !expected.contains_key(key) {
                    return Some(format!("{path}.{key}: extra in Rust output"));
                }
            }
            None
        }
        (Value::Array(expected), Value::Array(actual)) => {
            if expected.len() != actual.len() {
                return Some(format!(
                    "{path}: expected {} items, Rust produced {}",
                    expected.len(),
                    actual.len()
                ));
            }
            for (index, (expected_value, actual_value)) in expected.iter().zip(actual).enumerate() {
                if let Some(difference) =
                    first_difference(&format!("{path}[{index}]"), expected_value, actual_value)
                {
                    return Some(difference);
                }
            }
            None
        }
        _ => (expected != actual)
            .then(|| format!("{path}: expected {expected}, Rust produced {actual}")),
    }
}

#[test]
fn every_fixture_matches_the_js_extractor() {
    let fixtures = collect_fixtures();
    assert!(
        fixtures.len() >= 12,
        "expected at least 12 fixtures, found {}",
        fixtures.len()
    );

    let mut parser = Parser::new();
    let specs = supported_specs();
    let mut failures = Vec::new();
    for fixture in &fixtures {
        let spec = specs
            .iter()
            .find(|spec| spec.language == fixture.language)
            .expect("spec for fixture language");
        parser
            .set_language(&grammar(&fixture.language))
            .expect("grammar loads");
        let tree = parser
            .parse(&fixture.source, None)
            .expect("parse produces a tree");
        let extraction = extract_file(&tree, &fixture.source, &spec);
        let actual = serde_json::to_value(&extraction).expect("extraction serializes");
        if let Some(difference) = first_difference(&fixture.name, &fixture.expected, &actual) {
            failures.push(difference);
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {} fixtures differ from the JS extractor:\n{}",
        failures.len(),
        fixtures.len(),
        failures.join("\n")
    );
}

#[test]
fn each_fixture_has_at_least_one_definition() {
    // Guards the parity test against a silent "everything parsed to nothing" pass: the
    // fixtures are chosen so every one of them names at least one declaration.
    let fixtures = collect_fixtures();
    for fixture in &fixtures {
        let definitions = fixture.expected["definitions"]
            .as_array()
            .expect("expected definitions array");
        assert!(
            !definitions.is_empty(),
            "{} has no expected definitions; the fixture is not exercising extraction",
            fixture.name
        );
    }
    let languages: std::collections::HashSet<&str> =
        fixtures.iter().map(|fixture| fixture.language.as_str()).collect();
    let mut languages: Vec<&str> = languages.into_iter().collect();
    languages.sort_unstable();
    assert_eq!(languages, vec!["javascript", "jsx", "tsx", "typescript"]);
}
